import { test, expect } from '@playwright/test'
import type { Page } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'

const password = 'test workflow password!'
async function account(page: Page) {
  const email = 'e2e-'+crypto.randomUUID()+'@example.com'
  await page.goto('/register')
  await page.getByLabel('Display name').fill('Alex Morgan')
  await page.getByLabel('Email').fill(email)
  await page.getByLabel('Password').fill(password)
  await page.getByRole('button',{name:'Create account'}).click()
  await expect(page.getByRole('heading',{name:'Welcome, Alex.'})).toBeVisible()
  return email
}
async function draft(page: Page, title: string) {
  await page.goto('/studio/polls/new')
  await page.getByLabel('Question',{exact:true}).fill(title)
  await page.getByLabel('Description',{exact:false}).fill('Choose the option that best fits your team.')
  await page.getByLabel('Choice 1',{exact:true}).fill('Build together')
  await page.getByLabel('Choice 2',{exact:true}).fill('Explore first')
  await page.getByRole('button',{name:'Save draft'}).click()
  await expect(page.getByRole('heading',{name:title,exact:true})).toBeVisible()
}
test('creator, mobile guest and independent spectator see the same live vote', async ({ page,browser })=>{
  const email = await account(page)
  await draft(page,'What should we tackle next?')
  await page.getByRole('link',{name:'Edit draft'}).click()
  await page.getByLabel('Description',{exact:false}).fill('Choose a direction for the next workshop.')
  await page.getByRole('button',{name:'Add choice'}).click()
  await page.getByLabel('Choice 3',{exact:true}).fill('Reflect on feedback')
  await page.getByRole('button',{name:'Save draft'}).click()
  await page.getByRole('button',{name:'Publish poll'}).click()
  const link = page.getByRole('textbox',{name:'Share link'})
  await expect(link).toBeVisible()
  const url = await link.inputValue()
  const guestContext = await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true})
  const spectatorContext = await browser.newContext()
  try {
    const guest = await guestContext.newPage()
    const spectator = await spectatorContext.newPage()
    await guest.goto(url)
    await spectator.goto(url)
    await expect(spectator.getByText('0 votes',{exact:true})).toBeVisible()
    const a11y = await new AxeBuilder({page:guest}).withTags(['wcag2a','wcag2aa','wcag21aa']).analyze()
    expect(a11y.violations.map(v=>v.id)).toEqual([])
    await spectatorContext.setOffline(true)
    await expect(spectator.getByText('reconnecting',{exact:true})).toBeVisible()
    await guest.getByRole('radio',{name:'Build together'}).check()
    await guest.getByRole('button',{name:'Cast vote'}).click()
    await expect(guest.getByText('Vote received.',{exact:false})).toBeVisible()
    await spectatorContext.setOffline(false)
    await expect(spectator.getByText('1 vote',{exact:true})).toBeVisible()
    await expect(page.getByText('1 vote',{exact:true})).toBeVisible()
    await guest.reload()
    await expect(guest.getByText('Vote received.',{exact:false})).toBeVisible()
    await page.getByRole('button',{name:'Close poll'}).click()
    await expect(spectator.getByText('Voting has closed.')).toBeVisible()
    await page.getByRole('link',{name:'Analytics'}).click()
    await expect(page.getByRole('heading',{name:'Votes by hour'})).toBeVisible()
    const csv = await page.request.get(page.url().replace(/\/studio\/polls\/(.+)\/analytics/,'/api/v1/polls/$1/export'))
    expect(await csv.text()).toContain('Build together,1')
    await page.getByRole('button',{name:'Sign out'}).click()
    await expect(page.getByRole('heading',{name:/Read the room/})).toBeVisible()
    await page.getByRole('link',{name:'Sign in',exact:true}).click()
    await page.getByLabel('Email').fill(email)
    await page.getByLabel('Password').fill(password)
    await page.getByRole('button',{name:'Sign in'}).click()
    await expect(page.getByRole('heading',{name:'Welcome, Alex.'})).toBeVisible()
  } finally { await guestContext.close(); await spectatorContext.close() }
})

test('host advances a two-question room and presentation follows without reload', async ({page,browser})=>{
  await account(page)
  await draft(page,'Which session format works best?')
  await draft(page,'Which topic comes next?')
  await page.goto('/studio/rooms/new')
  await page.getByLabel('Room name').fill('Design workshop')
  await page.getByRole('checkbox',{name:'Which session format works best?'}).check()
  await page.getByRole('checkbox',{name:'Which topic comes next?'}).check()
  await page.getByRole('button',{name:'Save room'}).click()
  await expect(page.getByRole('heading',{name:'Design workshop'})).toBeVisible()
  const url = await page.getByRole('textbox',{name:'Share link'}).inputValue()
  const audienceContext = await browser.newContext()
  try {
    const audience = await audienceContext.newPage()
    const screen = await audienceContext.newPage()
    await audience.goto(url)
    await screen.goto(url+'/present')
    await expect(audience.getByRole('heading',{name:'Waiting for the host'})).toBeVisible()
    await page.getByRole('button',{name:'Open question 1'}).click()
    await expect(audience.getByRole('heading',{name:'Which session format works best?'})).toBeVisible()
    await expect(screen.getByRole('heading',{name:'Which session format works best?'})).toBeVisible()
    await audience.getByRole('radio',{name:'Explore first'}).check()
    await audience.getByRole('button',{name:'Cast vote'}).click()
    await expect(screen.getByText('1 vote',{exact:true})).toBeVisible()
    await page.getByRole('button',{name:'Open question 2'}).click()
    await expect(audience.getByRole('heading',{name:'Which topic comes next?'})).toBeVisible()
    await expect(screen.getByRole('heading',{name:'Which topic comes next?'})).toBeVisible()
    await page.getByRole('button',{name:'End room'}).click()
    await expect(screen.getByRole('heading',{name:'This session has ended'})).toBeVisible()
  } finally { await audienceContext.close() }
})
